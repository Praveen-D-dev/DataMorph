import { NextRequest } from "next/server";
import { v4 as uuidv4 } from "uuid";
import { DatabaseService, DashboardRecord } from "@/services/database.service";
import { PythonBridgeService } from "@/services/python-bridge.service";
import { apiSuccess, apiError } from "@/utils/response";

export async function POST(req: NextRequest, { params }: { params: { id: string } }) {
  const startTime = Date.now();
  try {
    const dataset = await DatabaseService.getDatasetById(params.id);
    if (!dataset) {
      return apiError(`Dataset with ID '${params.id}' not found`, "ERR_NOT_FOUND", 404);
    }

    let title: string | undefined = undefined;
    try {
      const body = await req.json();
      if (body.title) title = body.title;
    } catch {}

    // Invoke Python Dashboard Synthesizer
    const dashConfig = await PythonBridgeService.generateDashboard(dataset.storage_path, title);

    const dashboardId = uuidv4();
    const dashboardRecord: DashboardRecord = {
      id: dashboardId,
      dataset_id: dataset.id,
      title: dashConfig.title,
      description: `Autogenerated adaptive dashboard for ${dataset.filename}`,
      layout_grid: dashConfig.layout_grid,
      is_active: true,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
      kpis: dashConfig.kpis,
      visualizations: dashConfig.visualizations,
      filters: dashConfig.filters,
      navigation_sections: dashConfig.navigation_sections
    };

    await DatabaseService.saveDashboard(dashboardRecord);
    return apiSuccess({ ...dashboardRecord, total_rows: dashConfig.total_rows, total_columns: dashConfig.total_columns }, 201, Date.now() - startTime);
  } catch (err: any) {
    return apiError(`Dashboard generation failed: ${err.message}`, "ERR_DASHBOARD_GEN_FAILED", 500);
  }
}
